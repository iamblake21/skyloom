"""Extract serialized Unity Mesh .asset files into deterministic Unreal-space OBJ files.

Unity stores meshes generated by editor tooling directly in YAML assets.  They
do not pass through the normal FBX/OBJ migration path, but the vertex and index
buffers are complete and lossless.  This tool decodes the channels needed by
the Starter Island water and underbody meshes and writes centimetre-scaled,
Unreal-axis OBJ files without modifying the Unity project.
"""

